// Builds the hero workbench: one test bed and three products that take turns on it.
//   node anatomy/workbench/build.mjs      writes src/components/hero/workbenchArt.ts
// The rover's geometry is settled and audited when rover.mjs loads (it exits on any problem).
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { BENCH, ROVER_ITEMS, ROVER_SOLIDS, W, H } from "./rover.mjs";
import { cabinet, fixture } from "./products.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "../../src/components/hero/workbenchArt.ts");

// Rover assemblies, bottom-up (the order it is put together). Its rocks ride with it.
const ROVER_ASMS = [
  { id: "stand", name: "Terrain" },
  { id: "susp.far", name: "Far rocker-bogie" },
  { id: "susp.near", name: "Near rocker-bogie" },
  { id: "wheels.far", name: "Far-side wheels" },
  { id: "wheels.near", name: "Near-side wheels" },
  { id: "body", name: "Warm electronics box" },
  { id: "rtg", name: "Power unit" },
  { id: "avionics", name: "Avionics bay" },
  { id: "deck", name: "Solar deck" },
  { id: "antenna", name: "Antennas" },
  { id: "mast", name: "Remote-sensing mast" },
];

const solidsIn = (svg) => (svg.match(/class="iso-solid/g) || []).length;

function pack({ id, code, name, asms, items, parts }) {
  const index = Object.fromEntries(asms.map((a, i) => [a.id, i]));
  for (const it of items) if (!(it.asm in index)) throw new Error(`${id}: item in unknown assembly ${it.asm}`);
  const svg = items.map((it) => `<g class="wb-it" data-asm="${index[it.asm]}">${it.svg}</g>`).join("");
  return { id, code, name, parts: parts ?? solidsIn(svg), asms: asms.map((a) => a.name), svg };
}

const rover = pack({
  id: "rover",
  code: "RV-01",
  name: "Planetary rover",
  asms: ROVER_ASMS,
  items: ROVER_ITEMS.map((it) => ({ asm: it.piece, svg: it.svg })),
  parts: ROVER_SOLIDS,
});

const products = [rover, pack(cabinet()), pack(fixture())];
const DATA = { W, H, bench: BENCH, products };

const banner = "// Generated by anatomy/workbench/build.mjs. Do not edit by hand.\n";
writeFileSync(OUT, `${banner}export const WORKBENCH = ${JSON.stringify(DATA)} as const;\n`);
console.log(
  `wrote workbenchArt.ts · ${products.map((p) => `${p.code} ${p.parts} parts / ${p.asms.length} asms`).join(" · ")} · ${(JSON.stringify(DATA).length / 1024).toFixed(0)} KB`,
);
